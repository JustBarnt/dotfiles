"""Builds the Windows menu: default/omarchy/omarchy-menu.jsonc.

Upstream's menu has 423 entries that drive Arch, pacman, Hyprland, systemd and omarchy-* scripts. The
Windows menu keeps the root layout (Apps, Setup, About, System) and swaps each action for something
that runs here: shell panels, ms-settings: pages, and shutdown/rundll32. Icons come from upstream
where an entry exists.

  python -I tools/build-menu.py

The first run copies upstream's file to default/omarchy/omarchy-menu.upstream.jsonc.
"""
import json
import os
import re
import shutil

MENU = "default/omarchy/omarchy-menu.jsonc"
UPSTREAM = "default/omarchy/omarchy-menu.upstream.jsonc"

if not os.path.exists(UPSTREAM):
    shutil.copyfile(MENU, UPSTREAM)

with open(UPSTREAM, encoding="utf8") as h:
    text = h.read()

upstream = {}
for m in re.finditer(r'^  "([a-z0-9.\-]+)": (\{.*\}),?\s*$', text, re.M):
    try:
        upstream[m.group(1)] = json.loads(m.group(2))
    except ValueError:
        pass


WINKEYS = 'powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$OMARCHY_PATH/tools/winkeys.ps1" '


def summon(plugin, payload="{}"):
    return "omarchy-shell shell summon " + plugin + " '" + payload + "'"


# (id, label, fallback glyph, action | None, extra fields)
ENTRIES = [
    ("apps", None, None, None, {}),  # taken from upstream whole: provider "apps"
    ("appearance", "Style", "\U000f0b2f", None, {"aliases": ["style"]}),
    ("appearance.theme", "Theme", None, summon("omarchy.image-picker", '{"source":"themes"}'),
     {"aliases": ["theme", "themes"]}),
    ("appearance.background", "Background", None, summon("omarchy.image-picker", '{"source":"wallpapers"}'),
     {"aliases": ["background", "wallpaper"]}),
    ("trigger", "Trigger", "\U000f0e9e", None, {}),
    ("trigger.emoji", "Emoji", "\U000f0785", WINKEYS + "emoji 400", {"aliases": ["emoji"]}),
    ("trigger.clipboard", "Clipboard history", "\U000f0147", WINKEYS + "clipboard 400", {"aliases": ["clipboard"]}),
    ("setup", "Setup", "\U000f0493", None, {"aliases": ["settings"]}),
    ("setup.audio", "Audio", "\U000f057e", summon("omarchy.audio"), {}),
    ("setup.bluetooth", "Bluetooth", "\U000f00af", summon("omarchy.bluetooth"), {}),
    ("setup.network", "Network", None, summon("omarchy.network"), {"aliases": ["network"]}),
    ("setup.power", "Power", "\U000f0079", summon("omarchy.power"), {}),
    ("setup.windows-settings", "Windows Settings", "\U000f0493", "explorer.exe ms-settings:", {}),
    ("about", "About", None, "explorer.exe ms-settings:about", {}),
    ("system", "System", None, None, {"aliases": ["power-menu"]}),
    ("system.lock", "Lock", None, "rundll32.exe user32.dll,LockWorkStation", {}),
    ("system.sleep", "Sleep", "\U000f04b2", "rundll32.exe powrprof.dll,SetSuspendState 0,1,0", {}),
    ("system.logout", "Sign out", None, "shutdown.exe //l", {}),
    ("system.reboot", "Restart", None, "shutdown.exe //r //t 0", {}),
    ("system.shutdown", "Shut down", None, "shutdown.exe //s //t 0", {}),
]

lines = []
for key, label, glyph, action, extra in ENTRIES:
    up = upstream.get(key, {})
    if key == "apps":
        entry = dict(up)
        # Upstream's action opens the dock's app grid, which this port does not have. Without an
        # action the row is a submenu: Enter lists the apps from the app library.
        entry.pop("action", None)
    else:
        entry = {"icon": up.get("icon") or glyph or "", "label": label}
        entry.update(extra)
        if action:
            entry["action"] = action
    lines.append('  %s: %s' % (json.dumps(key), json.dumps(entry, ensure_ascii=False)))

out = (
    "{\n"
    "  // Omarchy menu for Windows, generated by tools/build-menu.py. The full Arch/Hyprland menu is in\n"
    "  // omarchy-menu.upstream.jsonc. Add your own rows in ~/.config/omarchy/extensions/omarchy-menu.jsonc.\n\n"
    "  // Root Menu\n"
    + ",\n".join(lines)
    + "\n}\n"
)
with open(MENU, "w", encoding="utf8", newline="\n") as h:
    h.write(out)
print("wrote", MENU, "with", len(ENTRIES), "entries")
